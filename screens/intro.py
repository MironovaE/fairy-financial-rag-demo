import streamlit as st

from utils import go


def show():
    st.title("Сундук Мудрости")
    st.markdown(
        '<p class="subtitle">Финансовый советник Княжеского банка — RAG-пайплайн в декорациях русской сказки</p>',
        unsafe_allow_html=True,
    )

    st.markdown(
        """
Богатыри и царицы приходят в банк с финансовой целью. Система подбирает им продукты
и просит языковую модель сформулировать совет. На каждом шаге видно, что происходит
под капотом: какие продукты отсеялись, что нашёл поиск и какой промпт ушёл в модель.

**Шаги пайплайна**

1. Загрузка профилей героев — демо-набор или свой JSON.
2. Вход по последним четырём цифрам карты.
3. Вопрос героя.
4. Загрузка продуктов банка — демо-набор или свой JSON.
5. Фильтрация по правилам: возраст, доход, гражданство. Как в настоящих банках,
   она идёт до поиска, чтобы модель не советовала то, что герою не положено.
6. Семантический поиск в векторной базе Chroma по эмбеддингам `sentence-transformers`,
   правила там же — условием `where`. Если базы нет — те же векторы в памяти, если модель
   не загрузилась — TF-IDF, если и он недоступен — ключевые слова.
7. Ответ модели через Groq (gpt-oss-20b). Если API недоступен, показывается шаблонный ответ.
        """
    )

    st.caption(
        "Эмбеддинги продуктов считаются один раз. Chroma живёт в памяти, у каждой сессии своя коллекция: "
        "чужие данные вы не увидите, а при новом каталоге она собирается заново."
    )

    st.button("Начать", type="primary", on_click=go, args=("profile_loader",))
